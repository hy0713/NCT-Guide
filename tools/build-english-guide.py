"""Build English walkthroughs from original English and actual native-game traces.

Usage: python tools/build-english-guide.py E:/nct [--check]
No game files or route data are modified. --check compares generated bytes.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIFFICULTIES = {1.33: 'Cakewalk', .97: 'Normal', .95: 'Hard', .90: 'Impossible'}
MODES = {'1': 'Default', '2': 'Proportional'}


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalogue = read(args.game / 'localization/stories/catalogue.json')
    scenarios = {s['scope']: s for s in catalogue['scenarios']}
    texts = {}
    for record in catalogue['records']:
        if record['collection'] not in ('questions_json', 'answers_json') or record['field'] != 'description':
            continue
        key = (record['scope'], record['collection'], record['location']['pk'])
        assert hashlib.sha256(record['source'].encode()).hexdigest() == record['sha256'], key
        texts.setdefault(key, set()).add(record['source'])
    runtime = (ROOT / 'guide/achievement-data.js').read_text(encoding='utf-8')
    data = json.loads(runtime.split('window.NCTAchievementData=', 1)[1].rstrip().removesuffix(';'))
    rules = data['rules']
    editorial = read(ROOT / 'achievements/english-editorial.json')
    coverage = read(ROOT / 'achievements/route-coverage.json')
    rows = {r['id']: r for r in coverage['rows']}
    routes = {r['id']: r for r in read(ROOT / 'achievements/community-routes.json')['routes']}
    audit = read(ROOT / 'achievements/source-audit.json')
    predicates = {r['id']: r for r in audit['achievements']}
    assert set(editorial) == set(rows) == {r['id'] for r in rules} == set(predicates)
    assert len(rules) == 31 and coverage['actualUnlocks'] == 31
    replays = read(ROOT / 'tests/verified-route-results.json')
    assert replays['status'] == 'passed'
    extra = read(ROOT / 'tests/whatbelt-neighbor-results.json')
    procedural = read(ROOT / 'tests/procedural-achievement-results.json')
    assert procedural['status'] == 'passed'
    records = {}
    for run in replays['runs'] + extra['runs']:
        if run.get('unlocked') and run.get('language') == 'en-US':
            records.setdefault(run['route'], (run, 'tests/verified-route-results.json' if run in replays['runs'] else 'tests/whatbelt-neighbor-results.json'))
    destiny = next(c for c in procedural['cases'] if c.get('achievement') == 'destiny' and c.get('language') == 'en-US')
    assert destiny['unlocked'] and len(destiny['games']) == 7
    for game in destiny['games']:
        records[game['route']] = ({**game['played'], 'seed': game['seed']}, 'tests/procedural-achievement-results.json')

    outputs = {}
    manifest = []
    links = {}
    used_files = {}
    answer_count = visit_count = 0
    for rule in rules:
        aid = rule['id']
        selected = rows[aid]['verifiedRoutes'] if aid == 'destiny' else rows[aid]['verifiedRoutes'][:1]
        links[aid] = []
        for selected_route in selected:
            rid = selected_route['id']
            route = routes[rid]
            scenario = scenarios[route['scope']]
            source = args.game / scenario['file']
            assert sha(source) == scenario['sourceSha256'], ('Scenario snapshot changed', source)
            used_files[scenario['file']] = scenario['sourceSha256']
            run, report = records[rid]
            steps = run['steps']
            assert sum(s['type'] == 'answer' for s in steps) == 25
            if aid == 'destiny':
                result = run['result']
                assert result['achievements']['threeosix'][scenario['year']]
                own = next(r for r in result['overall'] if r['candidate'] == scenario['candidate'])
                electoral = own['electoral_votes']
            else:
                assert run['scope'] == route['scope'] and run['achievement'] == aid
                electoral = run['electoral']
                route_payload = [route['scope'], route['answers'], route['visits'], route['difficulty'], route['mode']]
                expected = hashlib.sha256(json.dumps(route_payload, ensure_ascii=False, separators=(',', ':')).encode()).hexdigest()
                assert expected == run['routeSHA256'], ('Route changed since replay', rid)
            setup = f"{scenario['year']} — {scenario['candidateName']} / {scenario['runningMateName']}"
            path = f'achievements/walkthroughs/{rid}.md'
            label = f"{setup}; {MODES[route['mode']]}; {DIFFICULTIES[route['difficulty']]} ({route['difficulty']})"
            links[aid].append((rid, label, f'walkthroughs/{rid}.md'))
            lines = [f"# {rule['english']}", '', '[All achievements](../README.md) · [Live coach](../LIVE_COACH.md)', '',
                     f'**Setup:** {label}.', '', f"**Goal:** {editorial[aid]['goal']}", '',
                     f'**Recorded result:** {electoral} electoral votes; ' + ('year recorded in the cumulative save.' if aid == 'destiny' else 'native achievement unlocked.'), '',
                     'Match the question and answer text, not an A/B/C position. Question order and option order can vary. The order below is the recorded game; visits follow that game’s visit opportunities.', '',
                     f"**Route origin:** { {'community':'Community route', 'model-search':'Source-model search', 'baseline-replay':'Ordinary-guide replay'}[route['origin']]}. [Route source]({route['source']}).", '',
                     editorial[aid]['tip'], '',
                     f"[Actual replay report](../../{report}) · Route `{rid}` · Test fixture seed `{run['seed']}` (used only by the test harness).", '',
                     '## Answers and visits', '']
            n = visits = 0
            if aid == 'destiny' and scenario['year'] == '1988':
                lines.extend(['The community source names Missouri and California without visit counts. This tested adaptation uses six Missouri visits, five California visits and a final Maryland visit.', ''])
            for step in steps:
                if step['type'] == 'answer':
                    n += 1
                    q, a = step['question'], step['id']
                    question_texts = texts[(route['scope'], 'questions_json', q)]
                    answer_texts = texts[(route['scope'], 'answers_json', a)]
                    assert len(question_texts) == len(answer_texts) == 1, ('Ambiguous used text', rid, q, a)
                    question = next(iter(question_texts))
                    answer = next(iter(answer_texts))
                    assert question.strip() and answer.strip()
                    # Validate against the original literal arrays, independently in tests/english-guide.cjs.
                    lines.extend([f'### Question {n}', '', question, '', f'**Choose:** {answer}', '', f'<small>Question ID {q}; answer ID {a}.</small>', ''])
                    if a not in route['answers'].get(str(q), []):
                        lines.extend(['This question is a gap in the source route. The answer above is the choice made by the live coach in this successful replay.', ''])
                    answer_count += 1
                else:
                    assert step['type'] == 'visit'
                    visits += 1
                    visit_count += 1
                    lines.extend([f"**Visit {visits}: {step['abbr']}.**", ''])
            if visits == 0:
                lines.extend(['This scenario has no state-visit stage.', ''])
            outputs[path] = '\n'.join(lines)
            manifest.append({'achievement': aid, 'route': rid, 'scope': route['scope'], 'page': path,
                             'report': report, 'seed': run['seed'], 'electoral': electoral,
                             'scenarioSHA256': scenario['sourceSha256'], 'steps': steps})

    overview = ['# Native achievement guide', '', '[English](README.md) · [简体中文](README_ZH.md) · [Install and play](../README.md)', '',
                'All 31 native achievements, with the actual source conditions and tested setups. Open a walkthrough for the original English questions, exact answer text and recorded state visits. Community MOD achievements are outside this guide.', '',
                '## Before starting', '',
                '- For ordinary achievements, leave BIGSHOT off, use an unmodified native scenario, and choose Default or Proportional mode. Sea to Shining Sea is excluded by the native eligibility check.',
                '- Unless an entry says otherwise, use Normal (0.97) or harder. Lower multipliers are harder. Follow the walkthrough’s exact mode, running mate and difficulty.',
                '- Keep the same browser and server address for cumulative achievements. Changing `localhost` to `127.0.0.1`, changing ports or clearing site data creates a different save.',
                '- Randomness remains active in normal play. These are recorded successful routes, not guaranteed outcomes. At most one new achievement is awarded by the native priority chain per game; check the actual saved unlock after the result.', '',
                '## Choose an achievement', '', '| Achievement | Exact goal | Walkthrough / procedure |', '| --- | --- | --- |']
    for rule in rules:
        aid = rule['id']
        page_links = '<br>'.join(f'[{label}]({url})' for _, label, url in links[aid]) or f'[Procedure](#{aid.lower()})'
        overview.append(f"| [{rule['english']}](#{aid.lower()}) | {editorial[aid]['goal']} | {page_links} |")
    overview.extend(['', '## Achievement details', ''])
    for rule in rules:
        aid = rule['id']
        overview.extend([f'<a id="{aid.lower()}"></a>', '', f"### {rule['english']}", '',
                         f"**Goal:** {editorial[aid]['goal']}", '', editorial[aid]['tip'], ''])
        overview.extend(f'- [Walkthrough: {label}]({url})' for _, label, url in links[aid])
        if aid == 'what':
            overview.append('- [One-game 2016a walkthrough](walkthroughs/why-2016a_Clinton_Booker-1-0.97-search.md); repeat eligible completions until the counter reaches 100.')
        p = predicates[aid]
        source_url = f"https://github.com/newcampaigntrail/newcampaigntrail.github.io/blob/{audit['baseCommit']}/{audit['source']}#L{p['line']}"
        overview.extend(['', f"[Native condition]({source_url}) · Stable achievement ID: `{aid}`.", ''])
    overview.extend(['## Evidence and maintenance', '',
                     '[Unlock coverage](COVERAGE.md) · [Live coach](LIVE_COACH.md) · [Sources](SOURCES.md) · [Mechanics](../guide/README.md)', '',
                     f"The existing coverage snapshot records {coverage['actualGames']} browser games and actual unlock evidence for all {coverage['actualUnlocks']} achievements. The walkthroughs above reuse those recorded games; generating these pages does not add new playthroughs.", '',
                     'English questions and answers are extracted from the preserved original scenario data. Run `python tools/build-english-guide.py <game-directory> --check` to verify the generated pages. Editorial conditions are maintained separately in `english-editorial.json`.', ''])
    outputs['achievements/README.md'] = '\n'.join(overview)
    cover = ['# Achievement unlock coverage', '', '[Achievement guide](README.md) · [简体中文](COVERAGE_ZH.md)', '',
             f"Coverage snapshot: `{coverage['date']}`. **{coverage['actualUnlocks']}/{coverage['total']} native achievements have actual unlock evidence**, across {coverage['actualGames']} recorded browser games.", '',
             'Games used the original answer/visit controls, with non-loopback requests blocked. Unlocks were read from the native save. Replay counts include deliberate search, failures and bilingual fixtures; they are not estimated success probabilities.', '',
             '| Achievement | Unlock evidence | Tested setup(s) |', '| --- | --- | --- |']
    for rule in rules:
        aid = rule['id']
        setups = '<br>'.join(f'[{label}]({url})' for _, label, url in links[aid]) or f'[Native procedure](README.md#{aid.lower()})'
        cover.append(f"| {rule['english']} | Recorded | {setups} |")
    cover.extend(['', '## Original evidence', '',
                  '- [Machine-readable coverage, including unsuccessful searches](route-coverage.json)',
                  '- [52 bilingual successful single-game replays](../tests/verified-route-results.json)',
                  '- [Final Rust Belt route and its failed neighbors](../tests/whatbelt-neighbor-results.json)',
                  '- [100 real 2016a completions, seven-year cumulative runs in both languages, and native BIGSHOT procedures](../tests/procedural-achievement-results.json)',
                  '- [Eight additional compact-interface regression games](../tests/compact-playthrough-results.json) (later than the 613-game snapshot).', '',
                  'The English edition supplies 34 complete 25-question recorded walkthroughs: 27 single-game routes and seven year-specific Destiny routes. The other three achievements use the completion-counter or native BIGSHOT procedures documented in the guide.', ''])
    outputs['achievements/COVERAGE.md'] = '\n'.join(cover)
    outputs['achievements/english-walkthroughs.json'] = json.dumps({'schema': 1, 'sourceCommit': audit['baseCommit'], 'walkthroughs': manifest}, ensure_ascii=False, indent=2) + '\n'
    for name, content in outputs.items():
        raw = content.encode('utf-8')
        target = ROOT / name
        if args.check:
            assert target.read_bytes() == raw, ('Generated page differs', name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    summary = {'status': 'passed', 'achievements': len(rules), 'walkthroughs': len(manifest),
               'originalEnglishAnswers': answer_count, 'recordedVisits': visit_count,
               'scenarioSnapshotsChecked': len(used_files), 'generatedFilesChecked': len(outputs),
               'gameFilesModified': 0, 'newGamesFromGeneration': 0}
    print(json.dumps(summary))


if __name__ == '__main__':
    main()
